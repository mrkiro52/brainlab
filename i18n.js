function applyTranslations(lang) {
  const t = TRANSLATIONS[lang];
  if (!t) return;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (t[key] !== undefined) el.textContent = t[key];
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.dataset.i18nHtml;
    if (t[key] !== undefined) el.innerHTML = t[key];
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (t[key] !== undefined) el.placeholder = t[key];
  });

  document.querySelectorAll('[data-i18n-list]').forEach(ul => {
    const key = ul.dataset.i18nList;
    if (t[key] && Array.isArray(t[key])) {
      ul.innerHTML = t[key].map(item => `<li>${item}</li>`).join('');
    }
  });

  localStorage.setItem('brainlab-lang', lang);
  document.documentElement.lang = lang;
  document.documentElement.classList.add('i18n-ready');

  document.querySelectorAll('.lang-option').forEach(opt => {
    opt.classList.toggle('active', opt.dataset.lang === lang);
  });

  const mobileBtns = document.querySelectorAll('.mobile-language-btn');
  if (mobileBtns[0]) mobileBtns[0].classList.toggle('active', lang === 'en');
  if (mobileBtns[1]) mobileBtns[1].classList.toggle('active', lang === 'ru');
}

function initI18n() {
  const savedLang = localStorage.getItem('brainlab-lang') || 'en';
  applyTranslations(savedLang);

  document.querySelectorAll('.lang-option').forEach(option => {
    option.addEventListener('click', () => applyTranslations(option.dataset.lang));
  });

  const mobileBtns = document.querySelectorAll('.mobile-language-btn');
  if (mobileBtns[0]) mobileBtns[0].addEventListener('click', () => applyTranslations('en'));
  if (mobileBtns[1]) mobileBtns[1].addEventListener('click', () => applyTranslations('ru'));
}

window.i18n = {
  apply: function () {
    applyTranslations(localStorage.getItem('brainlab-lang') || 'en');
  }
};

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}
